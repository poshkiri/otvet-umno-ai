export function buildGenerationPrompt(
  flow: FlowId,
  category: CategoryId,
  source: string,
): string {
  return [
    `Сценарий: ${FLOW_LABELS[flow]}.`,
    `Контекст: ${CATEGORY_LABELS[category]}.`,
    `Задача: ${FLOW_TASKS[flow]}`,
    "",
    "Материал пользователя:",
    source.trim(),
  ].join("\n");
}

export function buildRefinementPrompt(
  refinement: RefinementId,
  source: string,
  previousResult: string,
): string {
  return [
    `Переделай готовый ответ: сделай его ${REFINEMENT_LABELS[refinement]}.`,
    "Не добавляй вымышленных фактов. Верни только обновлённый ответ без разбора и комментариев.",
    "",
    "Исходная ситуация:",
    source,
    "",
    "Предыдущий результат:",
    previousResult,
  ].join("\n");
}
